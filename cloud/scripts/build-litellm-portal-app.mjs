import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const entryPoint = fileURLToPath(new URL("../src/litellm-portal/app.tsx", import.meta.url));
const outputFile = new URL("../src/litellm-portal/app.generated.ts", import.meta.url);

const result = await build({
  entryPoints: [entryPoint],
  bundle: true,
  format: "esm",
  platform: "browser",
  target: ["es2020"],
  jsx: "automatic",
  minify: true,
  write: false,
  define: {
    "process.env.NODE_ENV": "\"production\"",
  },
  legalComments: "none",
});

const js = result.outputFiles[0]?.text ?? "";
const output = `// This file is generated by scripts/build-litellm-portal-app.mjs.\n// Source: src/litellm-portal/app.tsx\n\nexport const portalAppJs = ${JSON.stringify(js)};\n`;

writeFileSync(outputFile, output);
